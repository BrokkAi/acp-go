#!/usr/bin/env python3
"""Capture the Rust schema crate's decode and encode outcomes for the generated hint cases.

cmd/acpgen generates decode cases for every schema package
(hints_gen_test.go). This script dumps them with
`go test -run TestDeserializeHints -args -hints.dump=...`, decodes each one with
a probe built on the pinned Rust schema crate (scripts/hintprobe), and writes
the outcomes to the package's testdata/hints_rust.json, which the generated
test compares the Go decoders and encoders with: the decode error, or the exact
serde_json::to_string output of the decoded value, kept as the string the probe
wrote and never parsed again, so the member order of a _meta and the digits of
its numbers stay exactly as Rust wrote them.

Run it from any directory after regenerating the schema packages. It needs
cargo; the probe pins the crate versions the reference Rust SDK resolves.
"""

import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
PROBE = ROOT / "scripts" / "hintprobe"
CRATE = "agent-client-protocol-schema 1.15.1"

# Schema package directory -> probe build. The stable pins are decoded with
# the stable Rust types; the unstable pins with every unstable feature on, as
# their schema artifacts are generated.
PACKAGES = {
    "schema": "stable",
    "schema/v2": "stable",
    "schema/unstable": "unstable",
    "schema/v2/unstable": "unstable",
}
FEATURES = {"stable": "unstable_protocol_v2", "unstable": "unstable,unstable_protocol_v2"}
# Rust paths of the defs that are not public types of the protocol module:
# ProtocolVersion lives at the crate root, and the v2 ErrorData only
# describes Error::data in the schema, a serde_json::Value in the Rust type.
RUST_PATHS = {
    ("v1", "ProtocolVersion"): "acp::ProtocolVersion",
    ("v2", "ProtocolVersion"): "acp::ProtocolVersion",
    ("v2", "ErrorData"): "serde_json::Value",
}


def dump_cases(package):
    """Return the header and requests the package's generated test dumps."""
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "requests.jsonl"
        subprocess.run(
            ["go", "test", "./" + package, "-run", "^TestDeserializeHints$", "-count=1",
             "-args", "-hints.dump=" + str(path)],
            cwd=ROOT, check=True, stdout=subprocess.DEVNULL,
        )
        lines = [json.loads(line) for line in path.read_text(encoding="utf-8").split("\n") if line.strip()]
    return lines[0], lines[1:]


def dispatch_source(types):
    """Render the probe's dispatch table for {protocol: set of type names}."""
    lines = [
        "// Generated by scripts/capture_hint_fixtures.py. Do not edit.",
        "use agent_client_protocol_schema as acp;",
        "",
        "use crate::run;",
        "",
    ]
    for protocol in ("v1", "v2"):
        if protocol == "v2":
            lines.append('#[cfg(feature = "unstable_protocol_v2")]')
        lines.append(f"pub fn {protocol}(name: &str, input: &str) -> Option<Result<String, String>> {{")
        lines.append("    match name {")
        for name in sorted(types.get(protocol, ())):
            path = RUST_PATHS.get((protocol, name), f"acp::{protocol}::{name}")
            lines.append(f'        "{name}" => Some(run::<{path}>(input)),')
        lines.append("        _ => {")
        lines.append("            let _ = input;")
        lines.append("            None")
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def run_probe(build, requests):
    """Build the probe for the requests' types and return its responses by id."""
    types = {}
    for req in requests:
        types.setdefault(req["pkg"], set()).add(req["type"])
    (PROBE / "src" / "dispatch.rs").write_text(dispatch_source(types))
    target = PROBE / "target" / build
    subprocess.run(
        ["cargo", "build", "--quiet", "--locked", "--features", FEATURES[build], "--target-dir", str(target)],
        cwd=PROBE, check=True,
    )
    binary = target / "debug" / ("acp-hintprobe" + (".exe" if os.name == "nt" else ""))
    out = subprocess.run(
        [str(binary)], input="".join(json.dumps(r) + "\n" for r in requests),
        capture_output=True, text=True, encoding="utf-8", check=True,
    ).stdout
    responses = {}
    # Split on newlines only: serde_json writes U+2028 and U+2029 unescaped,
    # and str.splitlines would split on them.
    for line in out.split("\n"):
        if not line.strip():
            continue
        resp = json.loads(line)
        responses[resp["id"]] = resp
    return responses


def fixtures(header, requests, responses):
    """Assemble the fixture document from the dumped cases and probe output."""
    cases = {}
    for req in requests:
        resp = responses[req["id"]]
        if resp.get("missing"):
            raise ValueError(f"the probe has no Rust type {req['pkg']}::{req['type']} for {req['id']}")
        outcome = {"input": req["input"]}
        if "encoded" in resp:
            outcome["encoded"] = resp["encoded"]
        else:
            outcome["error"] = resp["error"]
        cases[req["id"]] = outcome
    return {"pin": header["pin"], "protocol": header["pkg"], "crate": CRATE, "cases": cases}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("packages", nargs="*", default=list(PACKAGES), help="schema package directories")
    args = parser.parse_args()
    for package in args.packages:
        header, requests = dump_cases(package)
        doc = fixtures(header, requests, run_probe(PACKAGES[package], requests))
        path = ROOT / package / "testdata" / "hints_rust.json"
        path.parent.mkdir(exist_ok=True)
        path.write_text(json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)} ({len(requests)} cases)")


if __name__ == "__main__":
    main()
